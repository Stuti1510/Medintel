"""
MEDINTEL AI - LLM Provider Adapters
Supports Google Gemini, OpenAI, and a grounded offline Educational Demo Provider.
"""

import os
import json
import time
from abc import ABC, abstractmethod
from typing import Dict, Any, List

class BaseLLMProvider(ABC):
    @abstractmethod
    def generate(self, prompt: str, system_instruction: str) -> Dict[str, Any]:
        pass

class GeminiProvider(BaseLLMProvider):
    def __init__(self, api_key: str, model_name: str = "gemini-1.5-flash"):
        self.api_key = api_key
        self.model_name = model_name

    def generate(self, prompt: str, system_instruction: str) -> Dict[str, Any]:
        import httpx
        url = f"https://generativelanguage.googleapis.com/v1beta/models/{self.model_name}:generateContent?key={self.api_key}"
        payload = {
            "contents": [{"parts": [{"text": f"System Instructions: {system_instruction}\n\n{prompt}"}]}]
        }
        start = time.time()
        with httpx.Client(timeout=30.0) as client:
            resp = client.post(url, json=payload)
            resp.raise_for_status()
            data = resp.json()
            text = data["candidates"][0]["content"]["parts"][0]["text"]
            latency_ms = round((time.time() - start) * 1000, 2)
            return {
                "provider": "Google Gemini",
                "model_name": self.model_name,
                "text": text,
                "latency_ms": latency_ms,
                "mode": "API_LIVE"
            }

class OpenAIProvider(BaseLLMProvider):
    def __init__(self, api_key: str, model_name: str = "gpt-4o-mini"):
        self.api_key = api_key
        self.model_name = model_name

    def generate(self, prompt: str, system_instruction: str) -> Dict[str, Any]:
        import httpx
        url = "https://api.openai.com/v1/chat/completions"
        headers = {"Authorization": f"Bearer {self.api_key}", "Content-Type": "application/json"}
        payload = {
            "model": self.model_name,
            "messages": [
                {"role": "system", "content": system_instruction},
                {"role": "user", "content": prompt}
            ]
        }
        start = time.time()
        with httpx.Client(timeout=30.0) as client:
            resp = client.post(url, json=payload, headers=headers)
            resp.raise_for_status()
            data = resp.json()
            text = data["choices"][0]["message"]["content"]
            latency_ms = round((time.time() - start) * 1000, 2)
            return {
                "provider": "OpenAI",
                "model_name": self.model_name,
                "text": text,
                "latency_ms": latency_ms,
                "mode": "API_LIVE"
            }

